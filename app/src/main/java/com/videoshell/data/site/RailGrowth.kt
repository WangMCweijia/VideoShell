package com.videoshell.data.site

/**
 * 聚合搜索时左栏**随结果长出来**的那点算术（v1.0.67）。
 *
 * ## 它解决什么
 *
 * 用户的原话是「**没有结果的站源直接不在左侧显示，哪个站源出来了就展示哪一个站源，
 * 后续出来的就增量展示**」。
 *
 * 旧行为（v1.0.50 ~ v1.0.66）：左栏一进页面就按 `Store` 顺序**一次铺满全部站点**，
 * 条数等搜出来再逐个回填。十个站里八个没货时，左栏有八格是空的 —— 用户得逐格点进去
 * 才知道"这个站也没有"，而左栏本来最该告诉他的恰恰是「哪几个站真的有货」。
 *
 * 新行为：「聚合」恒在 0 号位，之后**只有确实有内容的站**，而且是**随到达增量长出来的**。
 *
 * ## 为什么抽成纯函数
 *
 * "这一格该不该出现""该插在什么位置""还要不要那个尾巴"——三件事漏掉任何一件都会出
 * 看起来像坏了的现象：漏第一件格子白回来了；插错位则左栏站名与右边结果对不上（最像
 * "点错了"）；尾巴漏算则没结果的站**再也点不回去**。它们与 Android 无关，抽出来就能在
 * 离线 harness 里逐条钉死（`tools/verify/RailGrowthTest.java`），而不是只能靠肉眼看。
 *
 * ## 顺序为什么是**站点顺序**，不是到达顺序
 *
 * 网格里每个站的那一块是**按站点顺序**插的（[AggSearch.insertAt]）。左栏若按到达顺序排，
 * 同一个站在左栏与网格里的相对位置会不一样 —— 用户来回对照时会以为点错了。
 * 所以这里统一用站点顺序：新站插到"排在它前面、且已经上栏的那些站"之后，
 * 界面用 `notifyItemInserted` 的插入动画表达"又长出来一个"。
 *
 * ## 单站模式为什么不走这一套
 *
 * 单站模式左栏的**唯一用途**就是"这个站没有、换个站看看"（v1.0.50 建这一页的全部理由）。
 * 把它藏起来等于把这个功能删掉。所以隐藏只发生在聚合模式；那一边的补救入口是
 * [needFooter] 算出来的尾巴格「显示全部」。
 */
object RailGrowth {

    /**
     * 这个站该不该在左栏占一格。
     *
     * 判据只有一条：**[AggSearch.block] 出来的那一块非空**。
     *
     * ⚠️ **失败的站不上栏**。它的 `block` 天然是空的，但"没连上"与"这个站没有这部片"
     * 是两件事 —— 后者是结论，前者是故障（要能重试）。把失败站当成"没结果"藏掉，
     * 用户就只会看到"全网都没有"，而真相是我们根本没问到。
     * 失败清单由 [com.videoshell.ui.SearchActivity] 状态行那条提示负责说清。
     *
     * 另外注意：被 [AggSearch.PER_SITE] 截断、或被滤掉无名条目的站**仍然是"有内容"**，
     * 照常上栏 —— 上栏与否只看"有没有东西可看"，与"是不是完整整页"无关。
     */
    fun shouldShow(h: AggSearch.SiteHits): Boolean = AggSearch.block(h).isNotEmpty()

    /**
     * 新上栏的那一格在左栏里的位置。
     *
     * **0 号位永远是「聚合」**（见 [com.videoshell.ui.SearchActivity] 的约定），
     * 所以返回值最小是 1。
     *
     * = `1 + 排在 key 前面、且已经上栏的站数`。先后由 key 在 [allKeys] 里的下标决定，
     * 而不是"谁先返回"—— 理由见文件头。
     *
     * ⚠️ 认不出 [key] 时（站点在搜索期间被删了、key 为空、或调用方给的 [allKeys] 不完整）
     * 返回**末尾**：插在末尾最多是"位置不理想"，而返回一个中间的可疑位置会让左栏站名与
     * 右边结果**错位**，那才是真正查不出的那种 bug。
     */
    fun insertAt(allKeys: List<String>, shownKeys: List<String>, key: String): Int {
        val at = allKeys.indexOf(key)
        if (at < 0) return shownKeys.size + 1
        var pos = 1
        for (k in shownKeys) {
            val i = allKeys.indexOf(k)
            if (i in 0 until at) pos++
        }
        return pos
    }

    /**
     * 左栏末尾还要不要那一格「显示全部」。
     *
     * 有站被藏起来时才要。它是**用户点回"没结果的站"的唯一入口** ——
     * 没有它，聚合模式下那些站从此在这一页里够不着，只能退出去重走
     * "换默认站 → 再搜一遍"，也就是 v1.0.50 建这一页时要消灭的那几步。
     *
     * 一个站都没有（`allKeys` 空）时不要：那时左栏本来就该只有「聚合」，
     * 凑一个尾巴只会让人以为"有站被藏了"。
     */
    fun needFooter(shownKeys: List<String>, allKeys: List<String>): Boolean =
        allKeys.isNotEmpty() && shownKeys.size < allKeys.size
}
